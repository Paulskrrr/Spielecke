  function getLang() {
    return global.Spielecke.Store.appGet(LANG_KEY, DEFAULT_LANG) || DEFAULT_LANG;
  }

  function setLang(lang) {
    global.Spielecke.Store.appSet(LANG_KEY, lang === "en" || lang === "es" ? lang : "de");
  }

  function t(key) {
    var lang = getLang();
    if (lang === "en") return key;
    var dict = lang === "es" ? ES : DE;
    return (dict.hasOwnProperty(key) ? dict[key] : key);
  }

  // Pick the current language's subtree from a bilingual content bundle shaped
  // { de: <content>, en: <content>, es?: <content> }. Games wrap their top-level content read in
  // L(...) and everything underneath stays plain strings, so module logic that
  // walks .label / .prompts / .items / .q etc. is unchanged. Falls back across
  // languages, and returns the value untouched if it isn't a bundle (so a plain
  // English content file keeps working until it's converted). Spanish falls back
  // to English, never German — a bundle without an `es` subtree (Hochadel) reads
  // as English in Spanish mode.
  function L(bundle) {
    if (!bundle || typeof bundle !== "object") return bundle;
    if (!bundle.de && !bundle.en) return bundle; // not a {de,en} bundle
    var lang = getLang();
    var sub = bundle[lang] || bundle.en || bundle.de;
    // Family Mode (pools.js) hides the grown-up pools app-wide. Looked up
    // lazily rather than captured: pools.js loads after this file, but L() only
    // ever runs at render/draw time, long after every script is in.
    var P = global.Spielecke.Pools;
    return P && P.familyFilter ? P.familyFilter(sub) : sub;
  }

  global.Spielecke = global.Spielecke || {};
  global.Spielecke.t = t;
  global.Spielecke.L = L;
  global.Spielecke.getLang = getLang;
  global.Spielecke.setLang = setLang;
